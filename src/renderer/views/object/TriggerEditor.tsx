import { useCallback, useEffect, useMemo, useRef, useState } from 'react'
import { useTranslation } from 'react-i18next'
import { ChevronRight, Info, Save, Undo2 } from 'lucide-react'
import type { DbObjectRef, TriggerDatabaseEvent, TriggerDef, TriggerEvent, TriggerTiming } from '@shared/model'
import { triggerCapabilities } from '@domain/objectCapabilities'
import { objectsKey, useWorkspace, type SessionState } from '../../stores/workspaceStore'
import { Badge, Button, Checkbox, Empty, Field, Input, Select, Spinner, cx } from '../../components/ui'
import { SqlEditor } from '../../components/editor/SqlEditor'
import { notify } from '../../stores/toast'
import { errorMessage } from '../../gateways/api'
import { StatementReviewDialog } from '../dialogs/StatementReviewDialog'

const DB_EVENTS: TriggerDatabaseEvent[] = ['CONNECT', 'DISCONNECT', 'TRANSACTION START', 'TRANSACTION COMMIT', 'TRANSACTION ROLLBACK']
/** Select value standing for Firebird database-level triggers in the Type field. */
const DATABASE_TYPE = 'DATABASE'

/**
 * Trigger form (like IBExpert's trigger editor): name, table, position, active, timing and events
 * in fields; only the body is edited as SQL. The full DDL is generated by the session's dialect.
 */
export function TriggerEditor({
  session,
  refObj,
  isNew,
  context,
  onSaved
}: {
  session: SessionState
  refObj?: DbObjectRef
  isNew: boolean
  /** New triggers: where they go (and the table, when created from a table). */
  context: { database?: string; schema?: string; table?: string }
  onSaved(ref: DbObjectRef): void
}) {
  const { t } = useTranslation()
  const engine = session.info.engine
  const caps = triggerCapabilities(engine)
  const [original, setOriginal] = useState<TriggerDef | null>(null)
  const [draft, setDraft] = useState<TriggerDef | null>(null)
  const [error, setError] = useState<string | null>(null)
  const [preview, setPreview] = useState<string[]>([])
  const [previewError, setPreviewError] = useState<string | null>(null)
  const [showPreview, setShowPreview] = useState(false)
  const [saving, setSaving] = useState(false)
  const objects = useWorkspace((s) => s.objects[objectsKey(session.id, context.database, context.schema)])

  const load = useCallback(async () => {
    try {
      if (isNew || !refObj) {
        const body = await session.client.call('triggerBodyTemplate', undefined)
        setOriginal(null)
        setDraft({
          name: '',
          database: context.database,
          schema: context.schema,
          table: context.table,
          timing: 'BEFORE',
          events: ['INSERT'],
          position: caps.position === 'editable' ? 0 : undefined,
          active: true,
          forEach: caps.forEach ? 'ROW' : undefined,
          body,
          editable: true
        })
      } else {
        const def = await session.client.call('getTrigger', { ref: refObj })
        setOriginal(def)
        setDraft(structuredClone(def))
      }
      setError(null)
    } catch (err) {
      setError(errorMessage(err))
    }
  }, [session, refObj, isNew, context.database, context.schema, context.table, caps.position, caps.forEach])

  useEffect(() => {
    void load()
  }, [load])

  // Tables and views of the container feed the "For table" list.
  useEffect(() => {
    if (!objects) void useWorkspace.getState().loadObjects(session.id, context.database, context.schema)
  }, [objects, session.id, context.database, context.schema])
  const tables = useMemo(
    () => (objects?.status === 'ok' ? objects.items.filter((o) => o.kind === 'table' || o.kind === 'view').map((o) => o.name).sort((a, b) => a.localeCompare(b)) : []),
    [objects]
  )

  const dirty = useMemo(() => isNew || JSON.stringify(draft) !== JSON.stringify(original), [draft, original, isNew])

  useEffect(() => {
    if (!draft || !dirty || !draft.editable) {
      setPreview([])
      return
    }
    const timer = setTimeout(() => {
      session.client
        .call('triggerStatements', { original, target: draft })
        .then((s) => {
          setPreview(s)
          setPreviewError(null)
        })
        .catch((e) => {
          setPreview([])
          setPreviewError(errorMessage(e))
        })
    }, 150)
    return () => clearTimeout(timer)
  }, [draft, original, dirty, session])

  const draftRef = useRef(draft)
  draftRef.current = draft
  /** Statements shown for confirmation (with the draft they were built from) before anything runs. */
  const [review, setReview] = useState<{ statements: string[]; target: TriggerDef } | null>(null)

  const save = async (): Promise<void> => {
    const target = draftRef.current
    if (!target || !target.editable || !dirty) return
    setSaving(true)
    try {
      // Fresh statements: the debounced preview may lag behind the last keystroke.
      const statements = await session.client.call('triggerStatements', { original, target })
      setReview({ statements, target: structuredClone(target) })
    } catch (err) {
      notify.error(err)
    } finally {
      setSaving(false)
    }
  }

  const execute = async (target: TriggerDef): Promise<void> => {
    const { ref } = await session.client.call('saveTrigger', { original, target })
    void useWorkspace.getState().loadObjects(session.id, context.database, context.schema, true)
    if (!isNew) {
      const def = await session.client.call('getTrigger', { ref })
      setOriginal(def)
      setDraft(structuredClone(def))
    }
    onSaved(ref)
  }

  if (error) return <Empty title={error} />
  if (!draft) {
    return (
      <div className="flex h-full items-center justify-center">
        <Spinner size={20} />
      </div>
    )
  }

  const set = (patch: Partial<TriggerDef>): void => setDraft((d) => (d ? { ...d, ...patch } : d))
  const readOnly = !draft.editable
  const toggleEvent = (e: TriggerEvent, on: boolean): void => {
    if (!caps.multipleEvents) return set({ events: [e] })
    set({ events: on ? [...draft.events, e] : draft.events.filter((x) => x !== e) })
  }
  const tableOptions = draft.table && !tables.includes(draft.table) ? [draft.table, ...tables] : tables

  return (
    <div
      className="flex h-full flex-col"
      onKeyDown={(e) => {
        if ((e.ctrlKey || e.metaKey) && e.key.toLowerCase() === 's') {
          e.preventDefault()
          void save()
        }
      }}
    >
      <div className="flex shrink-0 flex-wrap items-end gap-3 border-b border-border bg-panel px-3 py-2">
        <Field label={t('trigger.name')} className="w-60">
          <Input value={draft.name} disabled={readOnly} autoFocus={isNew} onChange={(e) => set({ name: e.target.value })} />
        </Field>
        {draft.databaseEvent ? (
          <Field label={t('trigger.databaseEvent')} className="w-60">
            <Select value={draft.databaseEvent} disabled={readOnly} onChange={(e) => set({ databaseEvent: e.target.value as TriggerDatabaseEvent })}>
              {DB_EVENTS.map((ev) => (
                <option key={ev} value={ev}>
                  ON {ev}
                </option>
              ))}
            </Select>
          </Field>
        ) : (
          <Field label={t('trigger.forTable')} className="w-60">
            <Select value={draft.table ?? ''} disabled={readOnly} onChange={(e) => set({ table: e.target.value || undefined })}>
              <option value="" disabled>
                {t('trigger.chooseTable')}
              </option>
              {tableOptions.map((name) => (
                <option key={name} value={name}>
                  {name}
                </option>
              ))}
            </Select>
          </Field>
        )}
        {caps.position !== 'none' && (
          <Field label={t('trigger.position')} className="w-24">
            <Input
              type="number"
              min={0}
              max={32767}
              value={draft.position ?? 0}
              disabled={readOnly || caps.position === 'readonly'}
              title={caps.position === 'readonly' ? t('trigger.positionReadOnly') : undefined}
              onChange={(e) => set({ position: Math.max(0, Math.min(32767, Number(e.target.value) || 0)) })}
            />
          </Field>
        )}
        {caps.active && (
          <div className="pb-1.5">
            <Checkbox checked={draft.active} disabled={readOnly} onChange={(v) => set({ active: v })} label={t('trigger.active')} />
          </div>
        )}
        <div className="ml-auto flex items-center gap-2 pb-0.5">
          {dirty && !isNew && <Badge tone="warning">{t('sessions.unsaved')}</Badge>}
          <Button icon={<Undo2 size={14} />} disabled={!dirty || isNew} onClick={() => setDraft(structuredClone(original))}>
            {t('common.discard')}
          </Button>
          <Button variant="primary" icon={<Save size={14} />} loading={saving} disabled={readOnly || !dirty || !preview.length} onClick={() => void save()}>
            {t('common.save')}
          </Button>
        </div>
      </div>

      <div className="flex shrink-0 flex-wrap items-end gap-x-4 gap-y-2 border-b border-border px-3 py-2">
        <Field label={t('trigger.type')} className="w-44">
          <Select
            value={draft.databaseEvent ? DATABASE_TYPE : draft.timing}
            disabled={readOnly}
            onChange={(e) => {
              const v = e.target.value
              if (v === DATABASE_TYPE) set({ databaseEvent: draft.databaseEvent ?? 'CONNECT', events: [] })
              else set({ timing: v as TriggerTiming, databaseEvent: undefined, events: draft.events.length ? draft.events : ['INSERT'] })
            }}
          >
            {caps.timings.map((tm) => (
              <option key={tm} value={tm}>
                {tm}
              </option>
            ))}
            {caps.databaseEvents && <option value={DATABASE_TYPE}>{t('trigger.databaseTrigger')}</option>}
          </Select>
        </Field>
        {!draft.databaseEvent && (
          <div className="flex items-center gap-4 pb-1.5" role="group" aria-label={t('trigger.events')}>
            {caps.events.map((ev) => (
              <Checkbox key={ev} checked={draft.events.includes(ev)} disabled={readOnly} onChange={(v) => toggleEvent(ev, v)} label={ev} />
            ))}
          </div>
        )}
        {caps.forEach && (
          <Field label={t('trigger.forEach')} className="w-36">
            <Select value={draft.forEach ?? 'ROW'} disabled={readOnly} onChange={(e) => set({ forEach: e.target.value as 'ROW' | 'STATEMENT' })}>
              <option value="ROW">ROW</option>
              <option value="STATEMENT">STATEMENT</option>
            </Select>
          </Field>
        )}
        {caps.when && (
          <Field label={t('trigger.when')} className="min-w-56 flex-1">
            <Input value={draft.when ?? ''} disabled={readOnly} placeholder="OLD.status IS DISTINCT FROM NEW.status" className="font-mono text-xs" onChange={(e) => set({ when: e.target.value || undefined })} />
          </Field>
        )}
        {engine === 'postgres' && (
          <Field label={t('trigger.function')} className="w-56">
            <Input
              value={draft.functionName ?? ''}
              disabled={readOnly}
              placeholder={`${draft.name || 'trigger'}_fn`}
              className="font-mono text-xs"
              onChange={(e) => set({ functionName: e.target.value || undefined })}
            />
          </Field>
        )}
      </div>

      {(readOnly || (engine === 'mysql' && !isNew && dirty)) && (
        <div className="flex shrink-0 items-center gap-2 border-b border-border bg-warning/10 px-3 py-1.5 text-xs text-warning">
          <Info size={13} />
          {readOnly ? draft.note : t('trigger.mysqlRecreate')}
        </div>
      )}

      <div className="min-h-0 flex-1">
        <SqlEditor value={draft.body} engine={engine} readOnly={readOnly} onChange={(body) => set({ body })} onSave={() => void save()} />
      </div>

      <div className="shrink-0 border-t border-border bg-panel">
        <button type="button" className="flex h-7 w-full items-center gap-1.5 px-2 text-xs font-medium text-muted hover:text-fg" onClick={() => setShowPreview(!showPreview)}>
          <ChevronRight size={13} className={cx('transition-transform', showPreview && 'rotate-90')} />
          {t('structure.preview')}
          {previewError && <span className="truncate font-normal text-danger">— {previewError}</span>}
        </button>
        {showPreview && (
          <pre className="selectable max-h-56 overflow-auto border-t border-border bg-sunken px-3 py-2 font-mono text-[12px] leading-relaxed">
            {preview.length ? preview.map((s) => `${s};`).join('\n\n') : t('trigger.noChanges')}
          </pre>
        )}
      </div>

      <StatementReviewDialog
        open={!!review}
        title={t('review.title', { name: review?.target.name ?? '' })}
        statements={review?.statements ?? []}
        engine={engine}
        isNew={isNew}
        onExecute={() => execute(review!.target)}
        onClose={() => setReview(null)}
      />
    </div>
  )
}

  /** Applies the trigger form; engines with transactional DDL run it in one transaction. */
  async saveTrigger(p: { original: TriggerDef | null; target: TriggerDef }): Promise<{ statements: string[]; ref: DbObjectRef }> {
    const db = this.require()
    const statements = db.dialect.triggerStatements(p.original, p.target)
    await this.runStatements(statements, p.target.database, hasTransactionalDdl(db.info.engine))
    return { statements, ref: { database: p.target.database, schema: p.target.schema, name: p.target.name.trim(), kind: 'trigger', table: p.target.table } }
  }

  /** DML statements of a trigger / routine with their execution plans (prepared on the metadata connection, never executed). */
  async getRoutineOperations(p: { ref: DbObjectRef }): Promise<RoutineOperation[]> {
    const db = this.require()
    const explain = db.meta.explainPlan?.bind(db.meta)
    const source = await db.inspector.getObjectDDL(p.ref)
    const out: RoutineOperation[] = []
    for (const s of extractDmlStatements(source)) {
      const op: RoutineOperation = { operation: s.operation, table: s.table, statement: s.statement }
      if (explain) {
        try {
          op.plan = await db.metaLock.run(() => explain(s.sql))
        } catch (err) {
          op.error = toErrorPayload(err).message
        }
      }
      out.push(op)
    }
    return out
  }

  async bulkAlterTables(p: { tables: DbObjectRef[]; ops: BulkTableOperations; dryRun?: boolean }) {
    const d = this.require().dialect
    const results: { table: string; statements: string[]; error?: string }[] = []
    for (const ref of p.tables) {
      const statements = d.bulkAlter(ref, p.ops)
      const entry: { table: string; statements: string[]; error?: string } = { table: d.qualify(ref), statements }
      if (!p.dryRun && statements.length) {
        try {
          await this.runStatements(statements, ref.database)
        } catch (err) {
          // Keep going: one failing table must not stop the rest.
          entry.error = toErrorPayload(err).message
        }
      }
      results.push(entry)
    }
    return { results }
  }

  async insertRows(p: { ref: DbObjectRef; columns: string[]; rows: CellValue[][] }): Promise<{ affected: number }> {
    if (!p.rows.length) return { affected: 0 }
    const db = this.require()
    const d = db.dialect
    const head = `INSERT INTO ${d.qualify(p.ref)} (${p.columns.map((c) => d.quoteIdent(c)).join(', ')}) VALUES`
    const tuple = (r: CellValue[]): string => `(${r.map((v) => d.literal(v)).join(', ')})`
    // Firebird has no multi-row VALUES; one statement per row inside a single transaction.
    const perStatement = db.info.engine === 'firebird' ? 1 : 500
    const statements: string[] = []
    for (let i = 0; i < p.rows.length; i += perStatement) statements.push(`${head} ${p.rows.slice(i, i + perStatement).map(tuple).join(', ')}`)
    return { affected: await this.runStatements(statements, p.ref.database, true) }
  }


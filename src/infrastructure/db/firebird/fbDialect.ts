import type { CellValue, ColumnDef, DbEngine, DbObjectRef, IndexDef, LobKind, ObjectKind, ServerUser, TableDataRequest, TableStructure, TriggerDef } from '@shared/model'
import { LOB_PREVIEW_CHARS } from '@domain/lob'
import type { TemplateContext } from '@domain/ports/database'
import { splitType } from '@domain/sql/columnType'
import { BaseDialect } from '../common/baseDialect'

const FB_TYPES_25 = [
  'SMALLINT', 'INTEGER', 'BIGINT', 'NUMERIC', 'DECIMAL', 'FLOAT', 'DOUBLE PRECISION', 'DATE', 'TIME', 'TIMESTAMP',
  'CHAR', 'VARCHAR', 'BLOB SUB_TYPE TEXT', 'BLOB SUB_TYPE BINARY'
]

const encode = (major: number, minor = 0): number => major * 10000 + minor * 100

export class FbDialect extends BaseDialect {
  readonly dataTypes: string[]
  protected readonly engine: DbEngine = 'firebird'

  constructor(protected readonly version: number) {
    super()
    this.booleanLiterals = version >= encode(3)
    const types = [...FB_TYPES_25]
    if (version >= encode(3)) types.push('BOOLEAN')
    if (version >= encode(4)) types.push('INT128', 'DECFLOAT(16)', 'DECFLOAT(34)', 'TIME WITH TIME ZONE', 'TIMESTAMP WITH TIME ZONE', 'BINARY', 'VARBINARY')
    this.dataTypes = types
  }

  /** Unquoted Firebird identifiers are upper case; quote anything else. */
  quoteIdent(name: string): string {
    if (/^[A-Z][A-Z0-9_$]*$/.test(name) && !RESERVED.has(name)) return name
    return '"' + name.replace(/"/g, '""') + '"'
  }

  qualify(ref: DbObjectRef): string {
    return ref.schema && this.version >= encode(6) ? `${this.quoteIdent(ref.schema)}.${this.quoteIdent(ref.name)}` : this.quoteIdent(ref.name)
  }

  override selectTableData(req: TableDataRequest): string {
    // FIRST/SKIP works on every supported version (2.5+).
    return `SELECT FIRST ${req.limit} SKIP ${req.offset} ${this.selectList(req)} FROM ${this.qualify(req.ref)}${this.whereAndOrder(req)}`
  }

  /**
   * Binary parameters are typed as BLOBs: as text BLOBs in the connection charset, the server
   * would transliterate a file put in a text column (and reject bytes that aren't valid UTF-8).
   */
  protected override placeholder(): string {
    return 'CAST(? AS BLOB SUB_TYPE BINARY)'
  }

  /**
   * Firebird transliterates text BLOBs on every read, casts included, and maps the bytes the column
   * charset lacks (0x81, 0x8D… in WIN1252) to 0x00. CHARACTER SET OCTETS strings are copied as they
   * are, so the BLOB goes out in OCTETS chunks, one row each (a row message holds 64 KB).
   */
  override selectLobBytes(ref: DbObjectRef, column: string, key: Record<string, CellValue>): string {
    const n = 32000
    const from = `FROM ${this.qualify(ref)} WHERE ${this.keyCondition(key)}`
    const col = this.quoteIdent(column)
    return [
      `EXECUTE BLOCK RETURNS (CHUNK VARCHAR(${n}) CHARACTER SET OCTETS) AS`,
      'DECLARE P INTEGER = 1;',
      'DECLARE L INTEGER;',
      'BEGIN',
      `  SELECT OCTET_LENGTH(${col}) ${from} INTO :L;`,
      '  WHILE (P <= L) DO',
      '  BEGIN',
      `    SELECT CAST(SUBSTRING(${col} FROM :P FOR ${n}) AS VARCHAR(${n}) CHARACTER SET OCTETS) ${from} INTO :CHUNK;`,
      '    SUSPEND;',
      `    P = P + ${n};`,
      '  END',
      'END'
    ].join('\n')
  }

  protected override lobPreview(column: string, kind: LobKind, charset?: string): string {
    if (kind === 'binary') return `OCTET_LENGTH(${column})`
    // SUBSTRING of a BLOB is still a BLOB (one more read per cell); a VARCHAR comes inline. Without
    // the column charset the VARCHAR takes the database default, and under NONE the server sends
    // the bytes untransliterated.
    const n = LOB_PREVIEW_CHARS
    const type = `VARCHAR(${n})${charset && /^\w+$/.test(charset) && !/^(NONE|OCTETS)$/i.test(charset) ? ` CHARACTER SET ${charset}` : ''}`
    return `CASE WHEN CHAR_LENGTH(${column}) > ${n} THEN CAST(SUBSTRING(${column} FROM 1 FOR ${n}) AS ${type}) || ASCII_CHAR(1) ELSE CAST(${column} AS ${type}) END`
  }

  override limitQuery(sql: string, limit: number): string {
    return `SELECT FIRST ${limit} * FROM (${sql}) LIMITED_QUERY`
  }

  protected override singleRowSuffix(): string {
    return ' ROWS 1'
  }

  columnDefinition(col: ColumnDef): string {
    if (col.generated) return `${this.quoteIdent(col.name)} COMPUTED BY (${col.generated.expression})`
    const parts = [this.quoteIdent(col.name), col.domain ?? col.fullType]
    if (col.charset && !col.domain && /CHAR|TEXT/i.test(col.fullType) && !/CHARACTER SET/i.test(col.fullType)) parts.push(`CHARACTER SET ${col.charset}`)
    if (col.identity && this.version >= encode(3)) {
      parts.push(col.identity === 'always' && this.version >= encode(4) ? 'GENERATED ALWAYS AS IDENTITY' : 'GENERATED BY DEFAULT AS IDENTITY')
    } else if (col.defaultValue !== undefined && col.defaultValue !== null) {
      parts.push(`DEFAULT ${col.defaultValue}`)
    }
    if (!col.nullable) parts.push('NOT NULL')
    if (col.collation) parts.push(`COLLATE ${col.collation}`)
    return parts.join(' ')
  }

  protected override tableConstraints(t: TableStructure): string[] {
    const out: string[] = []
    for (const idx of t.indexes) {
      if (idx.type === 'PRIMARY') out.push(`CONSTRAINT ${this.quoteIdent(idx.name)} PRIMARY KEY (${this.indexColumns(idx)})`)
      else if (idx.type === 'UNIQUE' && idx.constraint) out.push(`CONSTRAINT ${this.quoteIdent(idx.name)} UNIQUE (${this.indexColumns(idx)})`)
    }
    for (const fk of t.foreignKeys) out.push(this.foreignKeyClause(fk, t.ref))
    for (const ck of t.checks) out.push(this.checkClause(ck))
    return out
  }

  protected override createIndexStatements(t: TableStructure): string[] {
    return t.indexes.filter((i) => i.type !== 'PRIMARY' && !i.constraint).map((i) => this.createIndex(t.ref, i))
  }

  override createIndex(ref: DbObjectRef, idx: IndexDef): string {
    const unique = idx.type === 'UNIQUE' ? 'UNIQUE ' : ''
    const desc = idx.descending ? 'DESCENDING ' : ''
    const body = idx.expression ? `COMPUTED BY (${idx.expression})` : `(${this.indexColumns(idx)})`
    const where = idx.condition && this.version >= encode(5) ? ` WHERE ${idx.condition}` : ''
    return `CREATE ${unique}${desc}INDEX ${this.quoteIdent(idx.name)} ON ${this.qualify(ref)} ${body}${where}`
  }

  private comments(t: TableStructure): string[] {
    const out: string[] = []
    if (t.options.comment) out.push(`COMMENT ON TABLE ${this.qualify(t.ref)} IS ${this.quoteString(t.options.comment)}`)
    for (const c of t.columns) {
      if (c.comment) out.push(`COMMENT ON COLUMN ${this.qualify(t.ref)}.${this.quoteIdent(c.name)} IS ${this.quoteString(c.comment)}`)
    }
    return out
  }

  override createTable(t: TableStructure): string[] {
    return [...super.createTable(t), ...this.comments(t)]
  }

  /** Identity columns must be exact integers (Firebird answers "Unknow error" otherwise). */
  protected override validateTable(t: TableStructure): void {
    for (const c of t.columns) {
      if (!c.identity || this.version < encode(3) || c.domain) continue
      const { base, args } = splitType(c.fullType)
      const exact = /^(SMALLINT|INTEGER|INT|BIGINT|INT128)$/i.test(base) || (/^(NUMERIC|DECIMAL)$/i.test(base) && !/,\s*[1-9]/.test(args))
      if (!exact) throw new Error(`Identity needs an integer column ("${c.name}" is ${c.fullType})`)
    }
  }

  alterTable(original: TableStructure, targetTable: TableStructure): string[] {
    const target = this.prepareTable(targetTable)
    const ref = original.ref
    const table = this.qualify(ref)
    const out: string[] = []
    const dropConstraint = (name: string): string => `ALTER TABLE ${table} DROP CONSTRAINT ${this.quoteIdent(name)}`

    const fks = this.diffByName(original.foreignKeys, target.foreignKeys)
    for (const fk of fks.dropped) out.push(dropConstraint(fk.name))
    const checks = this.diffByName(original.checks, target.checks)
    for (const c of checks.dropped) out.push(dropConstraint(c.name))
    const idx = this.diffByName(original.indexes, target.indexes)
    for (const i of idx.dropped) out.push(i.type === 'PRIMARY' || i.constraint ? dropConstraint(i.name) : `DROP INDEX ${this.quoteIdent(i.name)}`)

    const cols = this.diffColumns(original, target)
    for (const c of cols.dropped) out.push(`ALTER TABLE ${table} DROP ${this.quoteIdent(c.name)}`)
    for (const { before, after } of cols.changed) {
      const alter = (n: string): string => `ALTER TABLE ${table} ALTER COLUMN ${this.quoteIdent(n)}`
      if (before.name !== after.name) out.push(`${alter(before.name)} TO ${this.quoteIdent(after.name)}`)
      const name = after.name
      if (after.generated) {
        if ((before.generated?.expression ?? '') !== after.generated.expression) out.push(`${alter(name)} COMPUTED BY (${after.generated.expression})`)
      } else if ((before.domain ?? before.fullType).toUpperCase() !== (after.domain ?? after.fullType).toUpperCase()) {
        out.push(`${alter(name)} TYPE ${after.domain ?? after.fullType}`)
      }
      if (before.nullable !== after.nullable) {
        if (this.version >= encode(3)) out.push(`${alter(name)} ${after.nullable ? 'DROP' : 'SET'} NOT NULL`)
        else {
          // Firebird 2.5 has no ALTER COLUMN ... NOT NULL; the system table flag is the documented workaround.
          out.push(
            `UPDATE RDB$RELATION_FIELDS SET RDB$NULL_FLAG = ${after.nullable ? 'NULL' : '1'} WHERE RDB$RELATION_NAME = ${this.quoteString(ref.name)} AND RDB$FIELD_NAME = ${this.quoteString(name)}`
          )
        }
      }
      if ((before.defaultValue ?? null) !== (after.defaultValue ?? null) && !after.identity) {
        out.push(after.defaultValue ? `${alter(name)} SET DEFAULT ${after.defaultValue}` : `${alter(name)} DROP DEFAULT`)
      }
      if ((before.comment ?? '') !== (after.comment ?? '')) {
        out.push(`COMMENT ON COLUMN ${table}.${this.quoteIdent(name)} IS ${after.comment ? this.quoteString(after.comment) : 'NULL'}`)
      }
    }
    for (const c of cols.added) {
      out.push(`ALTER TABLE ${table} ADD ${this.columnDefinition(c)}`)
      if (c.comment) out.push(`COMMENT ON COLUMN ${table}.${this.quoteIdent(c.name)} IS ${this.quoteString(c.comment)}`)
    }
    // Column order
    target.columns.forEach((col, i) => {
      const originalIndex = original.columns.findIndex((c) => c.name === (col.originalName ?? col.name))
      if (originalIndex !== -1 && originalIndex !== i) out.push(`ALTER TABLE ${table} ALTER ${this.quoteIdent(col.name)} POSITION ${i + 1}`)
    })
    for (const i of idx.added) {
      if (i.type === 'PRIMARY') out.push(`ALTER TABLE ${table} ADD CONSTRAINT ${this.quoteIdent(i.name)} PRIMARY KEY (${this.indexColumns(i)})`)
      else if (i.type === 'UNIQUE' && i.constraint) out.push(`ALTER TABLE ${table} ADD CONSTRAINT ${this.quoteIdent(i.name)} UNIQUE (${this.indexColumns(i)})`)
      else out.push(this.createIndex(ref, i))
    }
    for (const c of checks.added) out.push(`ALTER TABLE ${table} ADD ${this.checkClause(c)}`)
    for (const fk of fks.added) out.push(`ALTER TABLE ${table} ADD ${this.foreignKeyClause(fk, target.ref)}`)
    if ((original.options.comment ?? '') !== (target.options.comment ?? '')) {
      out.push(`COMMENT ON TABLE ${table} IS ${target.options.comment ? this.quoteString(target.options.comment) : 'NULL'}`)
    }
    if (target.ref.name !== ref.name) throw new Error('Firebird cannot rename tables')
    return out
  }

  override dropObject(ref: DbObjectRef): string {
    const kw: Record<string, string> = {
      table: 'TABLE', view: 'VIEW', procedure: 'PROCEDURE', function: 'FUNCTION', trigger: 'TRIGGER', sequence: 'SEQUENCE',
      domain: 'DOMAIN', exception: 'EXCEPTION', package: 'PACKAGE'
    }
    const k = kw[ref.kind]
    if (!k) throw new Error(`Cannot drop ${ref.kind} objects`)
    // Firebird 2.5 names sequences generators.
    const keyword = ref.kind === 'sequence' && this.version < encode(3) ? 'GENERATOR' : k
    return `DROP ${keyword} ${this.qualify(ref)}`
  }

  override truncateTable(ref: DbObjectRef): string {
    return `DELETE FROM ${this.qualify(ref)}`
  }

  renameObject(ref: DbObjectRef): string[] {
    throw new Error(`Firebird does not support renaming ${ref.kind} objects`)
  }

  /** Firebird has no CREATE TABLE ... LIKE; the session service rebuilds the table from its structure. */
  duplicateTable(): string[] {
    return []
  }

  maintenance(ref: DbObjectRef, action: 'optimize' | 'analyze' | 'check' | 'repair' | 'vacuum'): string[] {
    void ref
    void action
    return []
  }

  useDatabase(): string | null {
    return null
  }

  /** Firebird has no engines, per-table charsets, schemas (before 6) or owners to change in bulk. */
  bulkAlter(): string[] {
    return []
  }

  override setEnabled(ref: DbObjectRef, enabled: boolean): string[] {
    if (ref.kind !== 'trigger') return []
    return [`ALTER TRIGGER ${this.qualify(ref)} ${enabled ? 'ACTIVE' : 'INACTIVE'}`]
  }

  /** SET GENERATOR sets the current value on every version (2.5 to 5), unlike RESTART WITH whose semantics changed in 4.0. */
  override setSequenceValue(ref: DbObjectRef, value: string): string[] {
    return [`SET GENERATOR ${this.qualify(ref)} TO ${this.sequenceValue(value)}`]
  }

  override setExceptionMessage(ref: DbObjectRef, message: string): string[] {
    return [`ALTER EXCEPTION ${this.qualify(ref)} ${this.quoteString(message)}`]
  }

  triggerBodyTemplate(): string {
    return 'AS\nBEGIN\n  /* NEW.ID = GEN_ID(GENERATOR_NAME, 1); */\nEND'
  }

  /** CREATE OR ALTER TRIGGER; renames and table changes drop the old trigger first (DDL is transactional). */
  triggerStatements(original: TriggerDef | null, target: TriggerDef): string[] {
    const name = target.name.trim()
    if (!name) throw new Error('The trigger name is required')
    const state = target.active ? 'ACTIVE' : 'INACTIVE'
    let header: string
    if (target.databaseEvent) {
      header = `CREATE OR ALTER TRIGGER ${this.quoteIdent(name)}\n${state} ON ${target.databaseEvent} POSITION ${target.position ?? 0}`
    } else {
      if (!target.table) throw new Error('Choose the table of the trigger')
      if (!target.events.length) throw new Error('Choose at least one event (INSERT, UPDATE or DELETE)')
      const events = (['INSERT', 'UPDATE', 'DELETE'] as const).filter((e) => target.events.includes(e))
      header = `CREATE OR ALTER TRIGGER ${this.quoteIdent(name)} FOR ${this.quoteIdent(target.table)}\n${state} ${target.timing} ${events.join(' OR ')} POSITION ${target.position ?? 0}`
    }
    const body = /^\s*AS\b/i.test(target.body) ? target.body.trim() : `AS\n${target.body.trim()}`
    const out: string[] = []
    if (original && (original.name !== name || (original.table ?? '') !== (target.table ?? '') || !!original.databaseEvent !== !!target.databaseEvent)) {
      out.push(`DROP TRIGGER ${this.quoteIdent(original.name)}`)
    }
    out.push(`${header}\n${body}`)
    return out
  }

  createTemplate(kind: ObjectKind, ctx: TemplateContext): string {
    const psql = (body: string): string => `SET TERM ^ ;\n${body}^\nSET TERM ; ^\n`
    const table = ctx.table ? this.quoteIdent(ctx.table) : 'TABLE_NAME'
    switch (kind) {
      case 'view':
        return 'CREATE VIEW NEW_VIEW (ID) AS\nSELECT 1 FROM RDB$DATABASE;\n'
      case 'procedure':
        return psql('CREATE OR ALTER PROCEDURE NEW_PROCEDURE (P_ID INTEGER)\nRETURNS (RESULT INTEGER)\nAS\nBEGIN\n  RESULT = P_ID;\n  SUSPEND;\nEND')
      case 'function':
        if (this.version < encode(3)) throw new Error('PSQL functions need Firebird 3.0 or later')
        return psql('CREATE OR ALTER FUNCTION NEW_FUNCTION (P_ID INTEGER)\nRETURNS INTEGER\nAS\nBEGIN\n  RETURN P_ID;\nEND')
      case 'trigger': {
        const name = this.quoteIdent(`${(ctx.table ?? 'TABLE').toUpperCase().replace(/[^A-Z0-9_$]/g, '_')}_BI0`)
        return psql(`CREATE OR ALTER TRIGGER ${name} FOR ${table}\nACTIVE BEFORE INSERT POSITION 0\nAS\nBEGIN\n  /* NEW.ID = ...; */\nEND`)
      }
      case 'sequence':
        return this.version < encode(3) ? 'CREATE GENERATOR NEW_GENERATOR;\nSET GENERATOR NEW_GENERATOR TO 0;\n' : 'CREATE SEQUENCE NEW_SEQUENCE START WITH 0;\n'
      case 'exception':
        return "CREATE EXCEPTION NEW_EXCEPTION 'Message text';\n"
      case 'domain':
        return 'CREATE DOMAIN NEW_DOMAIN AS VARCHAR(100)\n  DEFAULT NULL\n  CHECK (VALUE IS NULL OR VALUE <> \'\');\n'
      default:
        throw new Error(`Firebird has no ${kind} objects`)
    }
  }

  userStatements(p: {
    action: 'create' | 'drop' | 'grant' | 'revoke' | 'password'
    user: ServerUser
    password?: string
    privileges?: string[]
    on?: string
  }): string[] {
    const user = this.quoteIdent(p.user.name)
    const privs = (p.privileges?.length ? p.privileges : ['ALL']).join(', ')
    switch (p.action) {
      case 'create':
        return [`CREATE USER ${user} PASSWORD ${this.quoteString(p.password ?? '')}`]
      case 'drop':
        return [`DROP USER ${user}`]
      case 'password':
        return [`ALTER USER ${user} PASSWORD ${this.quoteString(p.password ?? '')}`]
      case 'grant':
        if (!p.on) throw new Error('Firebird grants need a target object')
        return [`GRANT ${privs} ON ${p.on} TO ${user}`]
      case 'revoke':
        if (!p.on) throw new Error('Firebird revokes need a target object')
        return [`REVOKE ${privs} ON ${p.on} FROM ${user}`]
    }
  }
}

const RESERVED = new Set(
  (
    'ADD ADMIN ALL ALTER AND ANY AS AT AVG BEGIN BETWEEN BIGINT BIT_LENGTH BLOB BOOLEAN BOTH BY CASE CAST CHAR CHARACTER ' +
    'CHECK CLOSE COLLATE COLUMN COMMIT CONNECT CONSTRAINT COUNT CREATE CROSS CURRENT CURSOR DATE DAY DEC DECIMAL DECLARE ' +
    'DEFAULT DELETE DISCONNECT DISTINCT DOUBLE DROP ELSE END ESCAPE EXECUTE EXISTS EXTERNAL EXTRACT FALSE FETCH FILTER FLOAT ' +
    'FOR FOREIGN FROM FULL FUNCTION GLOBAL GRANT GROUP HAVING HOUR IN INDEX INNER INSERT INT INTEGER INTO IS JOIN LEADING LEFT ' +
    'LIKE LONG LOWER MAX MIN MINUTE MONTH NATIONAL NATURAL NCHAR NO NOT NULL NUMERIC OF ON ONLY OPEN OR ORDER OUTER POSITION ' +
    'PRECISION PRIMARY PROCEDURE REAL RECORD_VERSION REFERENCES RELEASE RETURNING_VALUES RETURNS REVOKE RIGHT ROLLBACK ROW_COUNT ' +
    'ROWS SAVEPOINT SECOND SELECT SENSITIVE SET SIMILAR SMALLINT SOME SQLCODE SQLSTATE START SUM TABLE THEN TIME TIMESTAMP TO ' +
    'TRAILING TRIGGER TRIM TRUE UNION UNIQUE UNKNOWN UPDATE UPPER USER USING VALUE VALUES VARCHAR VARIABLE VARYING VIEW WHEN ' +
    'WHERE WHILE WITH YEAR'
  ).split(' ')
)

import { describe, expect, it } from 'vitest'
import type { ColumnDef, IndexDef, TableStructure } from '@shared/model'
import { typeArguments } from '@domain/sql/typeArguments'
import { MariaDbDialect, MySqlDialect } from '@infrastructure/db/mysql-family/mysqlDialect'
import { PgDialect } from '@infrastructure/db/postgres/pgDialect'
import { FbDialect } from '@infrastructure/db/firebird/fbDialect'
import { SqliteDialect } from '@infrastructure/db/sqlite/sqliteDialect'

const col = (name: string, fullType: string, extra: Partial<ColumnDef> = {}): ColumnDef => ({ name, dataType: fullType.replace(/\(.*$/, '').toUpperCase(), fullType, nullable: true, ...extra })
const pk = (c: string): IndexDef => ({ name: 'PRIMARY', type: 'PRIMARY', columns: [c], constraint: true })
const table = (columns: ColumnDef[], indexes: IndexDef[] = []): TableStructure => ({ ref: { name: 't', kind: 'table' }, columns, indexes, foreignKeys: [], checks: [], options: {} })

describe('type arguments per engine', () => {
  it('knows which types reject or require arguments', () => {
    expect(typeArguments('postgres', 'integer')).toBe('none')
    expect(typeArguments('postgres', 'varchar')).toBe('optional')
    expect(typeArguments('firebird', 'BLOB SUB_TYPE TEXT')).toBe('none')
    expect(typeArguments('firebird', 'VARCHAR')).toBe('required')
    expect(typeArguments('mariadb', 'DATE')).toBe('none')
    expect(typeArguments('mysql', 'INT')).toBe('optional')
    expect(typeArguments('mysql', 'varchar')).toBe('required')
    expect(typeArguments('sqlite', 'DATE')).toBe('optional')
  })
})

describe('DDL the servers would reject', () => {
  it('drops arguments from types that take none', () => {
    expect(new PgDialect(180000).createTable(table([col('id', 'integer(10)'), col('d', 'date(3)'), col('n', 'numeric(10,2)')]))[0]).toBe(
      'CREATE TABLE t (\n  id integer,\n  d date,\n  n numeric(10,2)\n)'
    )
    expect(new FbDialect(50000).createTable(table([col('ID', 'INTEGER(10)'), col('T', 'BLOB SUB_TYPE TEXT(100)'), col('TS', 'TIMESTAMP(3)')]))[0]).toContain(
      '(\n  ID INTEGER,\n  T BLOB SUB_TYPE TEXT,\n  TS TIMESTAMP\n)'
    )
    expect(new MySqlDialect(90000).createTable(table([col('d', 'DATE(3)'), col('i', 'INT(10)'), col('f', 'DOUBLE(10)')]))[0]).toContain('`d` DATE NULL,\n  `i` INT(10) NULL,\n  `f` DOUBLE NULL')
  })

  it('asks for lengths the type needs', () => {
    expect(() => new MySqlDialect(90000).createTable(table([col('v', 'VARCHAR')]))).toThrow(/VARCHAR needs a length/)
    expect(() => new FbDialect(50000).createTable(table([col('V', 'VARCHAR')]))).toThrow(/VARCHAR needs a length/)
    expect(new PgDialect(180000).createTable(table([col('v', 'varchar')]))[0]).toContain('v varchar')
  })

  it('checks MySQL auto increment columns', () => {
    const my = new MariaDbDialect(110800)
    const id = col('id', 'INT', { nullable: false, autoIncrement: true })
    expect(my.createTable(table([id], [pk('id')]))[0]).toContain('AUTO_INCREMENT')
    expect(() => my.createTable(table([id]))).toThrow(/to be a key/)
    expect(() => my.createTable(table([id, { ...id, name: 'n' }], [pk('id')]))).toThrow(/Only one column/)
    expect(() => my.createTable(table([col('id', 'VARCHAR(10)', { autoIncrement: true })], [pk('id')]))).toThrow(/numeric column/)
  })

  it('checks identity column types', () => {
    expect(() => new PgDialect(180000).createTable(table([col('id', 'varchar(10)', { identity: 'by_default' })]))).toThrow(/smallint, integer or bigint/)
    expect(new PgDialect(180000).createTable(table([col('id', 'integer(10)', { identity: 'by_default' })]))[0]).toContain('id integer GENERATED BY DEFAULT AS IDENTITY')
    expect(() => new FbDialect(50000).createTable(table([col('ID', 'VARCHAR(10)', { identity: 'by_default' })]))).toThrow(/integer column/)
    expect(new FbDialect(50000).createTable(table([col('ID', 'NUMERIC(18,0)', { identity: 'by_default' })]))[0]).toContain('GENERATED BY DEFAULT AS IDENTITY')
  })

  it('applies the rules to ALTER TABLE too', () => {
    const original = table([col('id', 'integer', { nullable: false })], [pk('id')])
    const target = table([col('id', 'integer', { nullable: false }), col('d', 'date(3)')], [pk('id')])
    expect(new PgDialect(180000).alterTable(original, target)).toEqual(['ALTER TABLE t ADD COLUMN d date'])
    expect(() => new SqliteDialect(35301).alterTable(original, table([col('id', 'TEXT', { autoIncrement: true })], [pk('id')]))).toThrow(/integer column/)
  })
})

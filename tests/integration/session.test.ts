interface Collected {
  events: { name: string; payload: unknown }[]
}

function newService(c: Collected): SessionService {
  return new SessionService({
    openDatabase,
    openTunnel: async () => null,
    createWriter: createFileWriter,
    readText: readTextFile,
    emit: <K extends keyof WorkerEvents & string>(name: K, payload: WorkerEvents[K]) => {
      c.events.push({ name, payload })
    }
  })
}

const isMy = (e: DbEngine): boolean => e === 'mysql' || e === 'mariadb'

function setupScript(engine: DbEngine): string {
  if (isMy(engine)) {
    return `DROP TABLE IF EXISTS ost_items;
CREATE TABLE ost_items (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  price DECIMAL(10,2) DEFAULT 0,
  created DATETIME NULL,
  data BLOB NULL,
  note TEXT NULL,
  KEY idx_name (name)
);
INSERT INTO ost_items (id, name, price, created, data, note) VALUES
  (1, 'alpha', 1.50, '2024-01-02 03:04:05', X'DEADBEEF', 'first'),
  (2, 'beta', 2.25, NULL, NULL, 'it''s'),
  (3, 'gamma', 3.00, '2025-12-31 23:59:59', NULL, NULL);`
  }
  if (engine === 'postgres') {
    return `DROP TABLE IF EXISTS ost_items_copy CASCADE;
DROP TABLE IF EXISTS ost_items CASCADE;
CREATE TABLE ost_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL,
  price numeric(10,2) DEFAULT 0,
  created timestamp NULL,
  data bytea NULL,
  note text NULL
);
CREATE INDEX idx_name ON ost_items (name);
INSERT INTO ost_items (id, name, price, created, data, note) VALUES
  (1, 'alpha', 1.50, '2024-01-02 03:04:05', '\\xdeadbeef', 'first'),
  (2, 'beta', 2.25, NULL, NULL, 'it''s'),
  (3, 'gamma', 3.00, '2025-12-31 23:59:59', NULL, NULL);`
  }
  if (engine === 'sqlite') {
    return `DROP TABLE IF EXISTS ost_items_copy;
DROP TABLE IF EXISTS ost_items;
CREATE TABLE ost_items (
  id INTEGER PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  price TEXT DEFAULT '0',
  created DATETIME NULL,
  data BLOB NULL,
  note TEXT NULL
);
CREATE INDEX idx_name ON ost_items (name);
INSERT INTO ost_items (id, name, price, created, data, note) VALUES
  (1, 'alpha', '1.50', '2024-01-02 03:04:05', X'DEADBEEF', 'first'),
  (2, 'beta', '2.25', NULL, NULL, 'it''s'),
  (3, 'gamma', '3.00', '2025-12-31 23:59:59', NULL, NULL);`
  }
  return `RECREATE TABLE OST_ITEMS (
  ID INTEGER NOT NULL PRIMARY KEY,
  NAME VARCHAR(100) NOT NULL,
  PRICE NUMERIC(10,2) DEFAULT 0,
  CREATED TIMESTAMP,
  DATA BLOB SUB_TYPE BINARY,
  NOTE BLOB SUB_TYPE TEXT
);
CREATE INDEX IDX_NAME ON OST_ITEMS (NAME);
INSERT INTO OST_ITEMS (ID, NAME, PRICE, CREATED, DATA, NOTE) VALUES (1, 'alpha', 1.50, '2024-01-02 03:04:05', x'DEADBEEF', 'first');
INSERT INTO OST_ITEMS (ID, NAME, PRICE, CREATED, DATA, NOTE) VALUES (2, 'beta', 2.25, NULL, NULL, 'it''s');
INSERT INTO OST_ITEMS (ID, NAME, PRICE, CREATED, DATA, NOTE) VALUES (3, 'gamma', 3.00, '2025-12-31 23:59:59', NULL, NULL);`
}

/** A catalog query returning well over 100 rows. */
function manyRowsSql(engine: DbEngine): string {
  if (isMy(engine)) return 'SELECT * FROM information_schema.COLUMNS'
  if (engine === 'postgres') return 'SELECT g, g * 2 AS twice FROM generate_series(1, 10000) g'
  if (engine === 'sqlite') return 'WITH RECURSIVE g(n) AS (SELECT 1 UNION ALL SELECT n + 1 FROM g WHERE n < 10000) SELECT n, n * 2 AS twice FROM g'
  return 'SELECT * FROM RDB$FIELDS'
}

function sleepSql(engine: DbEngine): string | null {
  if (isMy(engine)) return 'SELECT SLEEP(20)'
  if (engine === 'postgres') return 'SELECT pg_sleep(20)'
  // SQLite has no sleep: an unbounded recursive CTE keeps the statement busy inside SQLite.
  if (engine === 'sqlite') return 'WITH RECURSIVE c(x) AS (SELECT 1 UNION ALL SELECT x + 1 FROM c) SELECT count(*) FROM c'
  return null
}

const name = (engine: DbEngine, n: string): string => (engine === 'firebird' ? n.toUpperCase() : n)


afterAll(() => rmSync(tmp, { recursive: true, force: true }))

interface Collected {
  events: { name: string; payload: unknown }[]
}

function newService(c: Collected): SessionService {
  return new SessionService({
    openDatabase,
    openTunnel: async () => null,
    createWriter: createFileWriter,
    readText: readTextFile,
    emit: <K extends keyof WorkerEvents & string>(name: K, payload: WorkerEvents[K]) => {
      c.events.push({ name, payload })
    }
  })
}

const isMy = (e: DbEngine): boolean => e === 'mysql' || e === 'mariadb'

function setupScript(engine: DbEngine): string {
  if (isMy(engine)) {
    return `DROP TABLE IF EXISTS ost_items;
CREATE TABLE ost_items (
  id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  price DECIMAL(10,2) DEFAULT 0,
  created DATETIME NULL,
  data BLOB NULL,
  note TEXT NULL,
  KEY idx_name (name)
);
INSERT INTO ost_items (id, name, price, created, data, note) VALUES
  (1, 'alpha', 1.50, '2024-01-02 03:04:05', X'DEADBEEF', 'first'),
  (2, 'beta', 2.25, NULL, NULL, 'it''s'),
  (3, 'gamma', 3.00, '2025-12-31 23:59:59', NULL, NULL);`
  }
  if (engine === 'postgres') {
    return `DROP TABLE IF EXISTS ost_items_copy CASCADE;
DROP TABLE IF EXISTS ost_items CASCADE;
CREATE TABLE ost_items (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name varchar(100) NOT NULL,
  price numeric(10,2) DEFAULT 0,
  created timestamp NULL,
  data bytea NULL,
  note text NULL
);
CREATE INDEX idx_name ON ost_items (name);
INSERT INTO ost_items (id, name, price, created, data, note) VALUES
  (1, 'alpha', 1.50, '2024-01-02 03:04:05', '\\xdeadbeef', 'first'),
  (2, 'beta', 2.25, NULL, NULL, 'it''s'),
  (3, 'gamma', 3.00, '2025-12-31 23:59:59', NULL, NULL);`
  }
  if (engine === 'sqlite') {
    return `DROP TABLE IF EXISTS ost_items_copy;
DROP TABLE IF EXISTS ost_items;
CREATE TABLE ost_items (
  id INTEGER PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  price TEXT DEFAULT '0',
  created DATETIME NULL,
  data BLOB NULL,
  note TEXT NULL
);
CREATE INDEX idx_name ON ost_items (name);
INSERT INTO ost_items (id, name, price, created, data, note) VALUES
  (1, 'alpha', '1.50', '2024-01-02 03:04:05', X'DEADBEEF', 'first'),
  (2, 'beta', '2.25', NULL, NULL, 'it''s'),
  (3, 'gamma', '3.00', '2025-12-31 23:59:59', NULL, NULL);`
  }
  return `RECREATE TABLE OST_ITEMS (
  ID INTEGER NOT NULL PRIMARY KEY,
  NAME VARCHAR(100) NOT NULL,
  PRICE NUMERIC(10,2) DEFAULT 0,
  CREATED TIMESTAMP,
  DATA BLOB SUB_TYPE BINARY,
  NOTE BLOB SUB_TYPE TEXT
);
CREATE INDEX IDX_NAME ON OST_ITEMS (NAME);
INSERT INTO OST_ITEMS (ID, NAME, PRICE, CREATED, DATA, NOTE) VALUES (1, 'alpha', 1.50, '2024-01-02 03:04:05', x'DEADBEEF', 'first');
INSERT INTO OST_ITEMS (ID, NAME, PRICE, CREATED, DATA, NOTE) VALUES (2, 'beta', 2.25, NULL, NULL, 'it''s');
INSERT INTO OST_ITEMS (ID, NAME, PRICE, CREATED, DATA, NOTE) VALUES (3, 'gamma', 3.00, '2025-12-31 23:59:59', NULL, NULL);`
}

/** A catalog query returning well over 100 rows. */
function manyRowsSql(engine: DbEngine): string {
  if (isMy(engine)) return 'SELECT * FROM information_schema.COLUMNS'
  if (engine === 'postgres') return 'SELECT g, g * 2 AS twice FROM generate_series(1, 10000) g'
  if (engine === 'sqlite') return 'WITH RECURSIVE g(n) AS (SELECT 1 UNION ALL SELECT n + 1 FROM g WHERE n < 10000) SELECT n, n * 2 AS twice FROM g'
  return 'SELECT * FROM RDB$FIELDS'
}

function sleepSql(engine: DbEngine): string | null {
  if (isMy(engine)) return 'SELECT SLEEP(20)'
  if (engine === 'postgres') return 'SELECT pg_sleep(20)'
  // SQLite has no sleep: an unbounded recursive CTE keeps the statement busy inside SQLite.
  if (engine === 'sqlite') return 'WITH RECURSIVE c(x) AS (SELECT 1 UNION ALL SELECT x + 1 FROM c) SELECT count(*) FROM c'
  return null
}

const name = (engine: DbEngine, n: string): string => (engine === 'firebird' ? n.toUpperCase() : n)

describe.skipIf(targets.length === 0)('session service against live databases', () => {
  describe.each(targets.map((t) => [t.id, t] as [string, Target]))('%s', (_id, target) => {
    const c: Collected = { events: [] }
    const svc = newService(c)
    const engine = target.engine
    let ref: DbObjectRef

    beforeAll(async () => {
      const info = await svc.connect({ profile: profileFor(target), secrets: { password: target.password } })
      expect(info.version).toBeGreaterThan(0)
      ref = { database: isMy(engine) ? target.database : postgresDb(engine, target), schema: engine === 'postgres' ? 'public' : undefined, name: name(engine, 'ost_items'), kind: 'table' }
      const summary = await svc.execute({ queryId: 'setup', sql: setupScript(engine), maxRows: 100, database: isMy(engine) ? target.database : undefined })
      const failed = summary.statements.find((s) => s.error)
      expect(failed?.error?.message ?? null).toBeNull()
    })

    afterAll(async () => {
      await svc.disconnect()
    })

    it('reports the right engine flavour', () => {
      expect(svc.serverInfo().engine).toBe(engine)
    })

    it('streams result sets in columnar chunks and truncates at maxRows', async () => {
      c.events = []
      const summary = await svc.execute({ queryId: 'many', sql: manyRowsSql(engine), maxRows: 50, chunkSize: 20 })
      expect(summary.statements[0].error).toBeUndefined()
      expect(summary.statements[0].truncated).toBe(true)
      expect(summary.statements[0].rowCount).toBe(50)
      const chunks = c.events.filter((e) => e.name === 'result:rows').map((e) => e.payload as WorkerEvents['result:rows'])
      expect(chunks.map((x) => x.rowCount)).toEqual([20, 20, 10])
      expect(chunks[0].columns.length).toBeGreaterThan(0)
      expect(chunks[0].columns[0].length).toBe(20)
    })

    it('reads typed values', async () => {
      const res = await svc.query({ sql: `SELECT ${q(engine, 'id')}, ${q(engine, 'name')}, ${q(engine, 'price')}, ${q(engine, 'created')}, ${q(engine, 'data')}, ${q(engine, 'note')} FROM ${q(engine, 'ost_items')} ORDER BY 1`, database: isMy(engine) ? target.database : undefined })
      expect(res.rows).toHaveLength(3)
      const [id, nm, price, created, data, note] = res.rows[0]
      expect(Number(id)).toBe(1)
      expect(nm).toBe('alpha')
      expect(String(price)).toBe('1.50')
      expect(String(created)).toMatch(/^2024-01-02 03:04:05/)
      expect(data).toBeInstanceOf(Uint8Array)
      expect(Array.from(data as Uint8Array)).toEqual([0xde, 0xad, 0xbe, 0xef])
      expect(note).toBe('first')
      expect(res.rows[1][5]).toBe("it's")
      expect(res.rows[2][4]).toBeNull()
    })

    it('lists objects and reads table structure and DDL', async () => {
      const objects = isMy(engine) ? await svc.listObjects({ database: target.database }) : engine === 'postgres' ? await svc.listObjects({ database: ref.database, schema: 'public' }) : await svc.listObjects({})
      expect(objects.some((o) => o.kind === 'table' && o.name === ref.name)).toBe(true)
      const s = await svc.getTableStructure({ ref })
      expect(s.columns.map((col) => col.name.toLowerCase())).toEqual(['id', 'name', 'price', 'created', 'data', 'note'])
      expect(s.columns[1].nullable).toBe(false)
      expect(s.indexes.find((i) => i.type === 'PRIMARY')?.columns.map((x) => x.toLowerCase())).toEqual(['id'])
      expect(s.indexes.some((i) => i.name.toLowerCase() === 'idx_name')).toBe(true)
      const ddl = await svc.getObjectDDL({ ref })
      expect(ddl.toUpperCase()).toContain('CREATE TABLE')
    })

    it('applies grid edits through generated SQL', async () => {
      const key = { [name(engine, 'id')]: 2 as CellValue }
      const up = await svc.applyRowChanges({ ref, changes: [{ kind: 'update', key, values: { [name(engine, 'name')]: 'beta 2', [name(engine, 'note')]: null } }] })
      expect(up.affected).toBe(1)
      const del = await svc.applyRowChanges({ ref, changes: [{ kind: 'delete', key: { [name(engine, 'id')]: 3 } }] })
      expect(del.affected).toBe(1)
      const ins = await svc.applyRowChanges({ ref, changes: [{ kind: 'insert', values: { [name(engine, 'id')]: 10, [name(engine, 'name')]: 'delta', [name(engine, 'data')]: new Uint8Array([1, 2, 3]) } }] })
      expect(ins.affected).toBe(1)
      const sql = svc.tableDataSql({ ref, offset: 0, limit: 10, orderBy: [{ column: name(engine, 'id'), desc: true }] })
      const res = await svc.query({ sql, database: isMy(engine) ? target.database : undefined })
      expect(res.rows.map((r) => Number(r[0]))).toEqual([10, 2, 1])
      expect(res.rows[1][1]).toBe('beta 2')
      expect(Array.from(res.rows[0][4] as Uint8Array)).toEqual([1, 2, 3])
    })

    it('alters a table from a structure diff', async () => {
      const original = await svc.getTableStructure({ ref })
      const target2 = structuredClone(original)
      target2.columns.push({ name: name(engine, 'qty'), dataType: 'INTEGER', fullType: engine === 'firebird' ? 'INTEGER' : isMy(engine) ? 'int(11)' : 'integer', nullable: true, defaultValue: '0' })
      // SQLite has no column comments.
      if (engine !== 'sqlite') target2.columns[5] = { ...target2.columns[5], comment: 'free text' }
      const statements = svc.generateTableDDL({ original, target: target2 })
      expect(statements.length).toBeGreaterThan(0)
      await svc.executeStatements({ statements, database: isMy(engine) ? target.database : undefined })
      const after = await svc.getTableStructure({ ref })
      expect(after.columns.map((col) => col.name.toLowerCase())).toContain('qty')
      if (engine !== 'sqlite') expect(after.columns.find((col) => col.name.toLowerCase() === 'note')?.comment).toBe('free text')
    })

    it('duplicates a table with its data', async () => {
      const copyName = name(engine, 'ost_items_copy')
      if (engine === 'firebird') await svc.query({ sql: `RECREATE TABLE ${copyName} (X INTEGER)` }).catch(() => undefined)
      else await svc.query({ sql: `DROP TABLE IF EXISTS ${isMy(engine) ? `\`${target.database}\`.` : ''}${copyName}`, database: isMy(engine) ? target.database : undefined })
      if (engine === 'firebird') await svc.query({ sql: `DROP TABLE ${copyName}` })
      await svc.objectAction({ ref, action: 'duplicate', newName: copyName, withData: true })
      const res = await svc.query({ sql: `SELECT COUNT(*) FROM ${q(engine, 'ost_items_copy')}`, database: isMy(engine) ? target.database : undefined })
      expect(Number(res.rows[0][0])).toBe(3)
      await svc.objectAction({ ref: { ...ref, name: copyName }, action: 'drop' })
    })

    // The driver widens NONE columns for UTF8 connections; past 64 KB a row crashed Firebird 2.5.
    it.skipIf(engine !== 'firebird')('reads wide CHARACTER SET NONE columns over a UTF8 connection', async () => {
      await svc.query({ sql: 'RECREATE TABLE OST_WIDE (ID INTEGER, BIG VARCHAR(32765) CHARACTER SET NONE, MID VARCHAR(2000) CHARACTER SET NONE, N NUMERIC(15,3))' })
      await svc.query({ sql: "INSERT INTO OST_WIDE VALUES (1, 'big', 'mid', 1.5)" })
      const res = await svc.query({ sql: 'SELECT * FROM OST_WIDE' })
      expect(res.rows[0].slice(1, 3)).toEqual(['big', 'mid'])
      expect(svc.serverInfo().engine).toBe('firebird')
      await svc.query({ sql: 'DROP TABLE OST_WIDE' })
    })

    // BLOBs are read in 64 KB requests: values span several requests and segments.
    it.skipIf(engine !== 'firebird')('reads large text and binary BLOBs whole', async () => {
      await svc.query({ sql: "RECREATE TABLE OST_BLOBS (ID INTEGER, T BLOB SUB_TYPE TEXT SEGMENT SIZE 16384, B BLOB SUB_TYPE 0)" })
      await svc.query({ sql: "INSERT INTO OST_BLOBS VALUES (1, '', '')" })
      const piece = 'abcdefghij'.repeat(3000)
      for (let i = 0; i < 10; i++) {
        await svc.query({ sql: `UPDATE OST_BLOBS SET T = T || '${piece}', B = B || '${piece}'` })
      }
      const res = await svc.query({ sql: 'SELECT T, B FROM OST_BLOBS' })
      expect(res.rows[0][0]).toBe(piece.repeat(10))
      expect(Buffer.from(res.rows[0][1] as Uint8Array).toString('latin1')).toBe(piece.repeat(10))
      await svc.query({ sql: 'DROP TABLE OST_BLOBS' })
    })

    // The Data tab selects previews/sizes of LOB columns and fetches the values by key.
    it.skipIf(engine === 'sqlite')('loads LOB columns on demand', async () => {
      const structure = await svc.getTableStructure({ ref })
      const lazy = structure.columns.flatMap((c) => {
        const kind = lobKind(engine, c)
        return kind ? [{ column: c.name, kind }] : []
      })
      const data = name(engine, 'data')
      expect(lazy.map((l) => l.column)).toContain(data)
      const id = name(engine, 'id')
      const sql = svc.tableDataSql({ ref, offset: 0, limit: 100, orderBy: [{ column: id, desc: false }], columns: structure.columns.map((c) => c.name), lazy })
      const res = await svc.query({ sql, database: ref.database })
      const at = (column: string): number => res.columns.findIndex((c) => c.name === column)
      expect(Number(res.rows[0][at(id)])).toBe(1)
      expect(Number(res.rows[0][at(data)])).toBe(4)
      const note = name(engine, 'note')
      if (lazy.some((l) => l.column === note)) {
        // Uncut previews are the value; cut ones end with the mark the server appends.
        expect(res.rows[0][at(note)]).toBe('first')
        await svc.applyRowChanges({ ref, changes: [{ kind: 'update', key: { [id]: 1 }, values: { [note]: 'é'.repeat(300) } }] })
        const cut = await svc.query({ sql, database: ref.database })
        expect(cut.rows[0][at(note)]).toBe('é'.repeat(256) + LOB_CUT_MARK)
        await svc.applyRowChanges({ ref, changes: [{ kind: 'update', key: { [id]: 1 }, values: { [note]: 'first' } }] })
      }
      const values = await svc.fetchCellValues({ ref, key: { [id]: 1 }, columns: [data] })
      expect(Array.from(values[0] as Uint8Array)).toEqual([0xde, 0xad, 0xbe, 0xef])
      await expect(svc.fetchCellValues({ ref, key: { [id]: 999 }, columns: [data] })).rejects.toThrow(/no longer exists/)
    })

    it('rejects writes in read-only queries (agent mode)', async () => {
      await expect(
        svc.query({ sql: `UPDATE ${q(engine, 'ost_items')} SET ${q(engine, 'name')} = 'x'`, readOnly: true, database: isMy(engine) ? target.database : undefined })
      ).rejects.toThrow()
      const res = await svc.query({ sql: `SELECT COUNT(*) FROM ${q(engine, 'ost_items')} WHERE ${q(engine, 'name')} = 'x'`, database: isMy(engine) ? target.database : undefined })
      expect(Number(res.rows[0][0])).toBe(0)
    })

    it('exports CSV and XLSX', async () => {
      const csv = join(tmp, `${target.id}.csv`)
      const out = await svc.exportQuery({
        operationId: 'exp',
        source: { ref, database: isMy(engine) ? target.database : undefined },
        options: { format: 'csv', filePath: csv, includeHeader: true, lineBreak: '\n' }
      })
      expect(out.rows).toBe(3)
      const lines = readFileSync(csv, 'utf8').trim().split('\n')
      expect(lines[0].toLowerCase()).toContain('name')
      expect(lines).toHaveLength(4)
      const xlsx = join(tmp, `${target.id}.xlsx`)
      await svc.exportQuery({ operationId: 'exp2', source: { ref, database: isMy(engine) ? target.database : undefined }, options: { format: 'xlsx', filePath: xlsx, includeHeader: true } })
      expect(readFileSync(xlsx).subarray(0, 2).toString()).toBe('PK')
    })

    it('dumps structure and data as SQL', async () => {
      const file = join(tmp, `${target.id}.sql`)
      await svc.dumpSql({
        operationId: 'dump',
        options: {
          filePath: file,
          databases: [ref.database ?? ''],
          tables: { [ref.database ?? '']: [ref.name] },
          createDatabase: false,
          dropDatabase: false,
          createTables: true,
          dropTables: false,
          data: 'insert',
          rowsPerInsert: 100,
          includeRoutines: false,
          includeViews: false,
          includeTriggers: false
        }
      })
      const text = readFileSync(file, 'utf8')
      expect(text.toUpperCase()).toContain('CREATE TABLE')
      expect(text).toContain('INSERT INTO')
      expect(text).toContain('delta')
    })

    it('returns host information', async () => {
      const host = await svc.hostInfo()
      // SQLite has no server, so no process list.
      if (engine !== 'sqlite') expect(host.processes.rows.length).toBeGreaterThan(0)
      expect(host.variables.rows.length).toBeGreaterThan(0)
    })

    it.skipIf(!sleepSql(engine))('cancels a running query', async () => {
      const started = Date.now()
      const running = svc.execute({ queryId: 'slow', sql: sleepSql(engine)!, maxRows: 10 })
      await new Promise((r) => setTimeout(r, 700))
      await svc.cancel({ queryId: 'slow' })
      const summary = await running
      expect(Date.now() - started).toBeLessThan(10_000)
      expect(summary.cancelled).toBe(true)
    })
  })
})

function postgresDb(engine: DbEngine, t: Target): string | undefined {
  return engine === 'postgres' ? t.database : undefined
}

function q(engine: DbEngine, ident: string): string {
  return engine === 'firebird' ? ident.toUpperCase() : ident
}

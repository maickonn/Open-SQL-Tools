let seq = 0
const RUN = Date.now().toString(36)

const isMy = (e: DbEngine): boolean => e === 'mysql' || e === 'mariadb'

function service(): SessionService {
  return new SessionService({
    openDatabase,
    openTunnel: async () => null,
    createWriter: createFileWriter,
    readText: readTextFile,
    files: backupFiles,
    nativeBackup: nativeBackupFor,
    emit: () => undefined
  })
}

async function connect(profile: ConnectionProfile, password: string): Promise<SessionService> {
  const svc = service()
  await svc.connect({ profile, secrets: { password } })
  return svc
}

async function run(svc: SessionService, sql: string): Promise<void> {
  const r = await svc.execute({ queryId: 'q', sql, maxRows: 1000 })
  const failed = r.statements.find((s) => s.error)
  if (failed) throw new Error(`${failed.error?.message}\n${failed.sql}`)
}

async function rows(svc: SessionService, sql: string): Promise<CellValue[][]> {
  return (await svc.query({ sql })).rows
}

const ALL_OBJECTS: BackupObjectKinds = {
  views: true,
  routines: true,
  triggers: true,
  sequences: true,
  domainsAndTypes: true,
  events: true,
  materializedViews: true,
  extensions: true
}

function options(databases: string[], patch: Partial<LogicalBackupOptions> = {}): LogicalBackupOptions {
  return {
    databases,
    objects: ALL_OBJECTS,
    sequenceValues: true,
    usersAndGrants: false,
    createDatabase: false,
    dropObjects: false,
    stripDefiners: true,
    includeOwners: false,
    consistentSnapshot: true,
    rowsPerInsert: 50,
    ...patch
  }
}


const q = (engine: DbEngine, name: string): string => (engine === 'firebird' ? name.toUpperCase() : name)

async function snapshot(svc: SessionService, engine: DbEngine): Promise<Record<string, CellValue[][]>> {
  const t = (n: string): string => q(engine, n)
  const out: Record<string, CellValue[][]> = {
    parent: await rows(svc, `SELECT ${t('id')}, ${t('name')}, ${t('parent_id')}, ${t('doubled')} FROM ${t('z_parent')} ORDER BY 1`),
    child: await rows(svc, `SELECT ${t('id')}, ${t('parent_id')}, ${t('note')}, ${t('data')} FROM ${t('a_child')} ORDER BY 1`),
    counter: await rows(svc, `SELECT ${t('n')} FROM ${t('counter')}`),
    view: await rows(svc, `SELECT ${t('id')} FROM ${t('v_top')} ORDER BY 1`)
  }
  // Wider than a 64 KB message once WIN1252 is converted to UTF8: read as OCTETS.
  if (engine === 'firebird') out.wide = await rows(svc, 'SELECT ID, W1, W18, OCTET_LENGTH(W1) FROM WIDE_1252 ORDER BY 1')
  return out
}

/** Creates an empty target database (or file) and a profile pointing at it. */
async function emptyTarget(target: Target, name: string): Promise<ConnectionProfile> {
  const base = profileFor(target)
  if (target.engine === 'sqlite') return { ...base, database: join(tmp, `${name}.db`) }
  if (target.engine === 'firebird') {
    const Firebird = (await import('node-firebird')).default
    // Files outlive test runs inside the container, and creating over one hangs: unique names.
    const database = `/var/lib/firebird/data/${name}_${RUN}.fdb`
    await new Promise<void>((resolve, reject) =>
      Firebird.create({ host: '127.0.0.1', port: target.port, user: target.user, password: target.password, database, pageSize: 8192 } as never, (err, db) => {
        if (err) return reject(err)
        db.detach(() => resolve())
      })
    )
    return { ...base, database }
  }
  const admin = await connect(base, target.password)
  await run(admin, `DROP DATABASE IF EXISTS ${name}`)
  await run(admin, `CREATE DATABASE ${name}${isMy(target.engine) ? ' CHARACTER SET utf8mb4' : ''}`)
  await admin.disconnect()
  return { ...base, database: name }
}

describe.each(targets.map((t) => [t.id, t] as const))('backup %s', (id, target) => {
  const engine = target.engine
  // MariaDB has sequences since 10.3.
  const mariaSequences = id !== 'mariadb102'
  const fbModern = engine === 'firebird' && id !== 'firebird25'
  let source = ''

  async function sourceSession(): Promise<SessionService> {
    source = `bk_src_${id}_${++seq}`.replace(/\W/g, '_')
    const profile = await emptyTarget(target, source)
    const svc = await connect(profile, target.password)
    await run(svc, fixture(engine, mariaSequences, fbModern))
    return svc
  }

  it.each([false, true])('round-trips a database through the built-in backup (gzip: %s)', async (gzip) => {
    const src = await sourceSession()
    const before = await snapshot(src, engine)
    const file = join(tmp, `${id}-${gzip ? 'gz' : 'plain'}.sql${gzip ? '.gz' : ''}`)
    const db = engine === 'sqlite' || engine === 'firebird' ? '' : source
    const result = await src.backupDatabase({ operationId: 'b', filePath: file, method: 'logical', compress: gzip, logical: options([db]) })
    expect(result.files).toEqual([file])
    expect(existsSync(`${file}.part`)).toBe(false)
    const text = gzip ? gunzipSync(readFileSync(file)).toString('utf8') : readFileSync(file, 'utf8')
    expect(text.startsWith('-- OST-Backup: ')).toBe(true)
    const info = await src.inspectBackupFile({ filePath: file })
    expect(info).toMatchObject({ kind: 'sql', compressed: gzip, header: { engine } })
    await src.disconnect()

    const targetProfile = await emptyTarget(target, `bk_dst_${id}_${++seq}`.replace(/\W/g, '_'))
    const dst = await connect(targetProfile, target.password)
    const r = await dst.restoreDatabase({ operationId: 'r', filePath: file, method: 'logical', stopOnError: true, singleTransaction: true, commitEvery: 100 })
    expect(r.errors).toBe(0)
    const after = await snapshot(dst, engine)
    expect(after).toEqual(before)
    // Counters continue after the restored rows.
    if (engine === 'mariadb' && mariaSequences) expect(Number((await rows(dst, 'SELECT NEXTVAL(s_mark)'))[0][0])).toBeGreaterThanOrEqual(1002)
    if (engine !== 'firebird') {
      await run(dst, `INSERT INTO z_parent (name) VALUES ('next')`)
      const next = await rows(dst, `SELECT MAX(id) FROM z_parent`)
      expect(Number(next[0][0])).toBe(100)
    } else {
      const g = await rows(dst, 'SELECT GEN_ID(G_PARENT, 0) FROM RDB$DATABASE')
      expect(String(g[0][0])).toBe('1000')
      if (fbModern) {
        await run(dst, 'INSERT INTO T_IDENT (V) VALUES (4)')
        expect(await rows(dst, 'SELECT ID FROM T_IDENT WHERE V = 4')).toEqual([[4]])
        expect(await rows(dst, 'SELECT F_TWICE(21) FROM RDB$DATABASE')).toEqual([[42]])
      }
    }
    await dst.disconnect()
  })

  // Firebird has no DROP … IF EXISTS: its restores go into a new database file.
  it.runIf(engine !== 'firebird')('restores over the existing database when objects are dropped first', async () => {
    const src = await sourceSession()
    const before = await snapshot(src, engine)
    const file = join(tmp, `${id}-over.sql`)
    const db = engine === 'sqlite' ? '' : source
    await src.backupDatabase({ operationId: 'b', filePath: file, method: 'logical', compress: false, logical: options([db], { dropObjects: true }) })
    // Changes made after the backup are undone by the restore.
    await run(src, `UPDATE ${q(engine, 'z_parent')} SET ${q(engine, 'name')} = 'changed'`)
    const r = await src.restoreDatabase({ operationId: 'r', filePath: file, method: 'logical', database: db || undefined, stopOnError: true, singleTransaction: true, commitEvery: 100 })
    expect(r.errors).toBe(0)
    expect(await snapshot(src, engine)).toEqual(before)
    await src.disconnect()
  })

  it('leaves out the tables that were not chosen', async () => {
    const src = await sourceSession()
    const file = join(tmp, `${id}-some.sql`)
    const db = engine === 'sqlite' || engine === 'firebird' ? '' : source
    const schema = engine === 'postgres' ? 'public' : undefined
    // a_child is left out (with its serial sequence on PostgreSQL); counter is structure only.
    // Firebird procedures use A_CHILD, so routines stay out there.
    const tables = { [db]: [{ schema, name: q(engine, 'z_parent'), data: true }, { schema, name: q(engine, 'counter'), data: false }] }
    await src.backupDatabase({ operationId: 'b', filePath: file, method: 'logical', compress: false, logical: options([db], { tables, objects: { ...ALL_OBJECTS, triggers: false, views: false, materializedViews: false, routines: engine !== 'firebird' } }) })
    const before = await rows(src, `SELECT ${q(engine, 'id')}, ${q(engine, 'name')} FROM ${q(engine, 'z_parent')} ORDER BY 1`)
    await src.disconnect()
    const dst = await connect(await emptyTarget(target, `bk_part_${id}_${++seq}`.replace(/\W/g, '_')), target.password)
    const r = await dst.restoreDatabase({ operationId: 'r', filePath: file, method: 'logical', stopOnError: true, singleTransaction: true, commitEvery: 100 })
    expect(r.errors).toBe(0)
    expect(await rows(dst, `SELECT ${q(engine, 'id')}, ${q(engine, 'name')} FROM ${q(engine, 'z_parent')} ORDER BY 1`)).toEqual(before)
    expect(Number((await rows(dst, `SELECT COUNT(*) FROM ${q(engine, 'counter')}`))[0][0])).toBe(0)
    await expect(dst.query({ sql: `SELECT 1 FROM ${q(engine, 'a_child')}` })).rejects.toThrow()
    await dst.disconnect()
  })

  it('cancels a backup without leaving files behind', async () => {
    const src = await sourceSession()
    const file = join(tmp, `${id}-cancel.sql`)
    const db = engine === 'sqlite' || engine === 'firebird' ? '' : source
    const p = src.backupDatabase({ operationId: 'c', filePath: file, method: 'logical', compress: false, logical: options([db]) })
    src.cancelOperation({ operationId: 'c' })
    await expect(p).rejects.toThrow(/cancel/i)
    expect(existsSync(file)).toBe(false)
    expect(existsSync(`${file}.part`)).toBe(false)
    await src.disconnect()
  })

  it.runIf(engine === 'firebird')('backs up and restores through the Firebird services (file on the server)', async () => {
    const src = await sourceSession()
    const before = await snapshot(src, engine)
    const fbk = `/tmp/ost_${id}_${RUN}.fbk`
    await src.backupDatabase({ operationId: 'n', filePath: '', method: 'firebird-service', compress: false, native: { serverPath: fbk } })
    const targetPath = `/var/lib/firebird/data/bk_svc_${id}_${RUN}.fdb`
    const restore = src.restoreDatabase({ operationId: 'r', filePath: fbk, method: 'firebird-service', stopOnError: true, singleTransaction: false, commitEvery: 100, file: { targetPath, replace: false } })
    if (!fbModern) {
      // Firebird 2.5's server crashed restoring through the services API while serving other attachments.
      await expect(restore).rejects.toThrow(/Firebird 2\.5/)
      await src.disconnect()
      return
    }
    await restore
    await src.disconnect()
    const copy = await connect({ ...profileFor(target), database: targetPath }, target.password)
    expect(await snapshot(copy, engine)).toEqual(before)
    await copy.disconnect()
  })

  it.runIf(engine === 'sqlite')('copies the file with the SQLite backup API', async () => {
    const src = await sourceSession()
    const before = await snapshot(src, engine)
    const file = join(tmp, 'native.db')
    await src.backupDatabase({ operationId: 'n', filePath: file, method: 'sqlite-file', compress: false })
    await src.disconnect()
    const copy = await connect({ ...profileFor(target), database: file }, '')
    expect(await snapshot(copy, engine)).toEqual(before)
    await copy.disconnect()
  })
})
